def ensure_english_xml_keys() -> None:
    text = ENGLISH_XML.read_text(encoding="utf-8")
    if "export_share_via" in text:
        return
    block = ["", "    <!-- Export / share -->"]
    for key, value in EXPORT_EN.items():
        esc = (
            value.replace("&", "&amp;")
            .replace("'", "\\'")
            .replace('"', '\\"')
        )
        block.append(f'    <string name="{key}">{esc}</string>')
    block.append("</resources>")
    if not text.rstrip().endswith("</resources>"):
        raise SystemExit("English strings.xml missing closing resources tag")
    text = re.sub(r"\s*</resources>\s*$", "\n" + "\n".join(block) + "\n", text)
    ENGLISH_XML.write_text(text, encoding="utf-8")
    print("Updated English strings.xml with export/error keys")


def patch_json(locale: str, updates: dict[str, str]) -> None:
    path = TRANSLATIONS / f"{locale}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    data.update(updates)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    ensure_english_xml_keys()

    for locale, insights in INSIGHTS.items():
        patch_json(locale, insights)
        print(f"insights -> {locale}")

    # Keep ms/my insights as-is; still add export keys
    for locale, exports in EXPORT_I18N.items():
        patch_json(locale, exports)
        print(f"export -> {locale}")

    print("Done. Run: python scripts/generate_locales.py")


if __name__ == "__main__":
    main()
