def _load_rest() -> None:
    """Load remaining locales from companion module data (keeps this file manageable)."""
    from patch_newest_i18n_more import MORE_TRANSLATIONS
    from patch_newest_i18n_asia import ASIA_TRANSLATIONS
    from patch_newest_i18n_sea_rtl import SEA_RTL_TRANSLATIONS

    TRANSLATIONS.update(MORE_TRANSLATIONS)
    TRANSLATIONS.update(ASIA_TRANSLATIONS)
    TRANSLATIONS.update(SEA_RTL_TRANSLATIONS)


def main() -> int:
    _load_rest()
    required = set(next(iter(TRANSLATIONS.values())))
    for loc, mapping in TRANSLATIONS.items():
        missing = required - set(mapping)
        extra = set(mapping) - required
        if missing or extra or len(mapping) != len(required):
            raise SystemExit(f"{loc}: key mismatch missing={sorted(missing)[:5]} extra={sorted(extra)[:5]}")

    for loc, mapping in sorted(TRANSLATIONS.items()):
        path = TRANSLATIONS_DIR / f"{loc}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        before = len(data)
        data.update(mapping)
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"{loc}: {before} -> {len(data)} (+{len(data) - before})")
    print(f"done: {len(TRANSLATIONS)} locales, {len(required)} keys each")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
